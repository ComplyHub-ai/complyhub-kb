  FROM supabase_migrations.schema_migrations;
  SELECT count(*) INTO v_archive_rows
  FROM supabase_migrations.schema_migrations_backup_20260904;
  SELECT count(*) - count(DISTINCT version) INTO v_duplicates
  FROM supabase_migrations.schema_migrations;
  SELECT count(*) INTO v_category_a
  FROM stage_a_local_files lf
  LEFT JOIN supabase_migrations.schema_migrations sm USING (version)
  WHERE sm.version IS NULL;
  SELECT count(*) INTO v_category_b
  FROM supabase_migrations.schema_migrations sm
  LEFT JOIN stage_a_local_files lf USING (version)
  WHERE lf.version IS NULL;
  SELECT count(*) INTO v_name_mismatches
  FROM supabase_migrations.schema_migrations sm
  JOIN stage_a_local_files lf USING (version)
  WHERE sm.name IS DISTINCT FROM lf.name;
  SELECT EXISTS (
    (SELECT version, name, statements FROM supabase_migrations.schema_migrations
     EXCEPT ALL
     SELECT version, name, statements FROM supabase_migrations.schema_migrations_backup_20260904)
    UNION ALL
    (SELECT version, name, statements FROM supabase_migrations.schema_migrations_backup_20260904
     EXCEPT ALL
     SELECT version, name, statements FROM supabase_migrations.schema_migrations)
  ) INTO v_archive_diff;
  SELECT EXISTS (
    ((SELECT lf.version, lf.name
      FROM stage_a_local_files lf
      JOIN supabase_migrations.schema_migrations sm USING (version)
      WHERE sm.name IS DISTINCT FROM lf.name)
     EXCEPT
     (SELECT version, name FROM stage_a_name_fixes))
    UNION ALL
    ((SELECT version, name FROM stage_a_name_fixes)
     EXCEPT
     (SELECT lf.version, lf.name
      FROM stage_a_local_files lf
      JOIN supabase_migrations.schema_migrations sm USING (version)
      WHERE sm.name IS DISTINCT FROM lf.name))
  ) INTO v_unexpected_mismatch;

  IF v_live_rows <> 4672 OR v_archive_rows <> 4672 OR v_archive_diff
     OR v_category_a <> 172 OR v_category_b <> 3794
     OR v_name_mismatches <> 23 OR v_duplicates <> 0 OR v_unexpected_mismatch THEN
    RAISE EXCEPTION
      'Stage A preflight failed: live=%, archive=%, archive_diff=%, A=%, B=%, names=%, duplicates=%, unexpected_name_set=%',
      v_live_rows, v_archive_rows, v_archive_diff, v_category_a, v_category_b,
      v_name_mismatches, v_duplicates, v_unexpected_mismatch;
  END IF;
END
$preflight$;

DO $delete_assert$
DECLARE v_rows_deleted bigint;
BEGIN
  WITH deleted AS (
    DELETE FROM supabase_migrations.schema_migrations sm
    WHERE NOT EXISTS (
      SELECT 1 FROM stage_a_local_files lf WHERE lf.version = sm.version
    )
    RETURNING 1
  )
  SELECT count(*) INTO v_rows_deleted FROM deleted;
  IF v_rows_deleted <> 3794 THEN
    RAISE EXCEPTION 'Stage A delete count was %, expected 3794', v_rows_deleted;
  END IF;
END
$delete_assert$;

DO $insert_assert$
DECLARE v_rows_inserted bigint;
BEGIN
  INSERT INTO supabase_migrations.schema_migrations (version, name, statements)
  SELECT version, name, NULL
  FROM stage_a_stamps
  ORDER BY version;
  GET DIAGNOSTICS v_rows_inserted = ROW_COUNT;
  IF v_rows_inserted <> 172 THEN
    RAISE EXCEPTION 'Stage A stamp count was %, expected 172', v_rows_inserted;
  END IF;
END
$insert_assert$;

DO $update_assert$
DECLARE v_rows_updated bigint;
BEGIN
  UPDATE supabase_migrations.schema_migrations sm
  SET name = nf.name
  FROM stage_a_name_fixes nf
  WHERE sm.version = nf.version
    AND sm.name IS DISTINCT FROM nf.name;
  GET DIAGNOSTICS v_rows_updated = ROW_COUNT;
  IF v_rows_updated <> 23 THEN
    RAISE EXCEPTION 'Stage A name-fix count was %, expected 23', v_rows_updated;
  END IF;
END
$update_assert$;

COMMIT;

-- Deliberately outside the transaction: this proves the committed ledger, not merely its pending state.
DO $post_commit$
DECLARE
  v_ledger_rows bigint;
  v_duplicates bigint;
  v_name_mismatches bigint;
  v_nonnull_stamps bigint;
  v_membership_diff boolean;
BEGIN
  SELECT count(*) INTO v_ledger_rows
  FROM supabase_migrations.schema_migrations;
  SELECT count(*) - count(DISTINCT version) INTO v_duplicates
  FROM supabase_migrations.schema_migrations;
  SELECT count(*) INTO v_name_mismatches
  FROM supabase_migrations.schema_migrations sm
  JOIN stage_a_local_files lf USING (version)
  WHERE sm.name IS DISTINCT FROM lf.name;
  SELECT count(*) INTO v_nonnull_stamps
  FROM supabase_migrations.schema_migrations sm
  JOIN stage_a_stamps s USING (version)
  WHERE sm.statements IS NOT NULL;
  SELECT EXISTS (
    (SELECT version FROM supabase_migrations.schema_migrations
     EXCEPT
     SELECT version FROM stage_a_local_files)
    UNION ALL
    (SELECT version FROM stage_a_local_files
     EXCEPT
     SELECT version FROM supabase_migrations.schema_migrations)
  ) INTO v_membership_diff;

  IF v_ledger_rows <> 1050 OR v_duplicates <> 0 OR v_name_mismatches <> 0
     OR v_nonnull_stamps <> 0 OR v_membership_diff THEN
    RAISE EXCEPTION
      'Stage A post-commit invariant failed: ledger=%, duplicates=%, names=%, nonnull_stamps=%, membership_diff=%',
      v_ledger_rows, v_duplicates, v_name_mismatches, v_nonnull_stamps, v_membership_diff;
  END IF;
END
$post_commit$;
